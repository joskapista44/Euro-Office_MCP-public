/**
 * The canonical handshake, a callCommand body: the manifest's identity fields and capability list, or a reason.
 * Reads nothing else and writes nothing.
 */
const HANDSHAKE_BODY = `
let bridge;
try { bridge = typeof Api.GetEuroOfficeBridge === 'function' ? Api.GetEuroOfficeBridge() : null; } catch (err) { bridge = null; }
if (!bridge || typeof bridge.manifest !== 'function') return { ok: false, reason: 'BRIDGE_UNAVAILABLE' };
let m;
try { m = bridge.manifest(); } catch (err) { return { ok: false, reason: 'BRIDGE_UNAVAILABLE' }; }
if (!m || typeof m !== 'object') return { ok: false, reason: 'MANIFEST_MISSING' };
return { ok: true, manifest: {
  bridgeVersion: m.bridgeVersion, documentServerVersion: m.documentServerVersion, patchVersion: m.patchVersion,
  capabilities: Array.isArray(m.capabilities) ? m.capabilities.map(c => (c && typeof c === 'object' ? { id: c.id, version: c.version, kind: c.kind, mutation: c.mutation } : null)) : null } };
`;

/**
 * Pure: a handshake result against the accepted runtime(s) -> { ok, runtimeId, manifest } | { ok: false, reason }.
 * `expected` is one runtime or an explicit list of runtimes; the match is EXACT (documentServerVersion AND patchVersion
 * of one list entry) and the runtimeId is the matched entry's own id.
 */
function classifyHandshake(r, expected) {
  if (!r || typeof r !== 'object' || typeof r.ok !== 'boolean') return { ok: false, reason: 'MANIFEST_MALFORMED' };
  if (!r.ok) return { ok: false, reason: typeof r.reason === 'string' && r.reason ? r.reason : 'MANIFEST_MALFORMED' };
  const m = r.manifest;
  const str = v => typeof v === 'string' && v.length > 0;
  if (!m || typeof m !== 'object' || !str(m.bridgeVersion) || !str(m.documentServerVersion) || !str(m.patchVersion) || !Array.isArray(m.capabilities)) {
    return { ok: false, reason: 'MANIFEST_MALFORMED' };
  }
  if (Number(m.bridgeVersion.split('.')[0]) !== BRIDGE_MAJOR) return { ok: false, reason: 'BRIDGE_VERSION_MISMATCH' };
  const accepted = (Array.isArray(expected) ? expected : [expected]).filter(e => e && typeof e === 'object');
  if (!accepted.some(e => m.documentServerVersion === e.documentServerVersion)) return { ok: false, reason: 'RUNTIME_VERSION_MISMATCH' };
  if (!accepted.some(e => m.documentServerVersion === e.documentServerVersion && m.patchVersion === e.patchVersion)) return { ok: false, reason: 'PATCH_VERSION_MISMATCH' };
  return { ok: true, runtimeId: runtimeIdOf(m), manifest: m };
}

